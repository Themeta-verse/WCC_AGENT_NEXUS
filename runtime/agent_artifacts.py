@dataclass
class VerificationArtifact(AgentArtifact):
    """Final independent verification outcome."""
    status: str = "PENDING"  # "VERIFIED", "FAILED", "PENDING"
    passed: bool = False
    independent: bool = True
    checks: dict[str, bool] = field(default_factory=dict)
    evidence_ids: list[str] = field(default_factory=list)
    summary: str = ""

    def __post_init__(self) -> None:
        self.artifact_type = "verification"
        self.agent_role = ROLE_VERIFIER
        # Truth boundary invariant: An agent's statement alone is model-generated
        # and therefore INFERRED and untrusted.
        if self.model_generated:
            self.reality = "INFERRED"
            self.untrusted = True
        super().__post_init__()
        valid_statuses = {"VERIFIED", "FAILED", "PENDING"}
        if self.status not in valid_statuses:
            raise ArtifactValidationError(f"Invalid verification status '{self.status}'. Valid: {sorted(valid_statuses)}")

    def validate(self) -> None:
        super().validate()
        if self.status == "VERIFIED" and not self.passed:
            raise ArtifactValidationError("Contradiction: status is 'VERIFIED' but passed is False")
        if self.passed and self.status != "VERIFIED":
            raise ArtifactValidationError("Contradiction: passed is True but status is not 'VERIFIED'")


ARTIFACT_TYPE_MAP: dict[str, Type[AgentArtifact]] = {
    "base": AgentArtifact,
    "plan": PlanArtifact,
    "patch": PatchArtifact,
    "test_suite": TestSuiteArtifact,
    "review": ReviewArtifact,
    "security_audit": SecurityAuditArtifact,
    "execution_result": ExecutionResultArtifact,
    "diagnostic": DiagnosticArtifact,
    "verification": VerificationArtifact,
}


def artifact_from_dict(data: dict[str, Any]) -> AgentArtifact:
    """Reconstruct a typed artifact from a dictionary using its artifact_type."""
    if not isinstance(data, dict):
        raise ArtifactValidationError("Input data must be a dictionary")
    artifact_type = data.get("artifact_type", "base")
    cls = ARTIFACT_TYPE_MAP.get(artifact_type)
    if cls is None:
        raise ArtifactValidationError(f"Unknown artifact_type '{artifact_type}'")

    # Create shallow copy to avoid mutating source
    kwargs = dict(data)
    # Instantiate typed artifact
    try:
        return cls(**kwargs)
    except TypeError as exc:
        raise ArtifactValidationError(f"Failed to instantiate {cls.__name__}: {exc}") from exc


def artifact_from_json(json_str: str) -> AgentArtifact:
    """Deserialize a typed artifact from a JSON string."""
    try:
        data = json.loads(json_str)
    except json.JSONDecodeError as exc:
        raise ArtifactValidationError(f"Invalid JSON string: {exc}") from exc
    return artifact_from_dict(data)
